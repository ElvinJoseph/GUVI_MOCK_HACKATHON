USE WAREHOUSE BANK_WH;
USE DATABASE BANK_DB;

-- Task
CREATE OR REPLACE TASK LOAD_CORE_TASK
WAREHOUSE=BANK_WH
SCHEDULE='1 MINUTE'
AS
BEGIN

INSERT INTO CORE.CUSTOMER_CORE SELECT * FROM ST_CUST;
INSERT INTO CORE.ACCOUNT_CORE SELECT * FROM ST_ACC;
INSERT INTO CORE.TRANSACTION_CORE SELECT * FROM ST_TRANS;
INSERT INTO CORE.LOAN_CORE SELECT * FROM ST_LOAN;
-- JSON FIXED EXTRACTION
INSERT INTO CORE.FRAUD_ALERT_CORE
SELECT
value:alertId::STRING,
value:transactionId::STRING,
value:fraudScore::FLOAT,
value:reason::STRING,
value:status::STRING
FROM ST_FRAUD, LATERAL FLATTEN(INPUT => RAW_DATA);

END;

ALTER TASK LOAD_CORE_TASK RESUME;

SHOW TASKS;